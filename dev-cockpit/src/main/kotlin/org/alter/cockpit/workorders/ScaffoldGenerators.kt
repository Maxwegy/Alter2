/** `recipe`: a production stub for the first recipe (item on object or item on item). */
class RecipeGenerator : ScaffoldGenerator {
    override val kind = "recipe"

    override fun supports(enrichment: Enrichment) = enrichment.kind == "recipe" && !enrichment.recipes.isNullOrEmpty()

    override fun generate(enrichment: Enrichment, params: Map<String, Any?>, ctx: ScaffoldContext): Scaffold {
        val id = (params["id"] as Number).toInt()
        val usedId = (params["usedId"] as? Number)?.toInt() ?: -1
        val recipe = enrichment.recipes!!.first()
        val onObject = params["type"] == "ITEM_ON_LOC"
        val material = enrichment.facts["material"] as? String ?: recipe.materials.firstOrNull()?.first ?: "item"
        val target = enrichment.page?.title ?: params["name"] as? String ?: "target"
        val itemName = ctx.itemName(material) ?: "item.${RscmNames.slug(material)}"
        val targetName = if (onObject) ctx.objName(id, target) else (ctx.itemName(target) ?: "item.${RscmNames.slug(target)}")
        val outputName = ctx.itemName(recipe.output) ?: "item.${RscmNames.slug(recipe.output)}"
        val pkg = ctx.objPackage()
        val cls = Kt.className("${recipe.output} from ${material}") + "Plugin"
        val skill = recipe.skill?.uppercase()?.replace(' ', '_')
        val code = buildString {
            append(Kt.header(pkg, enrichment.sources, "${recipe.output} from $material${if (onObject) " at $target" else " with $target"}.", listOf("org.alter.api.Skills", "org.alter.rscm.RSCM.getRSCM")))
            appendLine("class $cls(r: PluginRepository, world: World, server: Server) : KotlinPlugin(r, world, server) {")
            appendLine("    init {")
            appendLine("        ${if (onObject) "onItemOnObj(obj = ${Kt.str(targetName)}, item = ${Kt.str(itemName)})" else "onItemOnItem(item1 = ${Kt.str(itemName)}, item2 = ${Kt.str(targetName)})"} {")
            appendLine("            player.queue { make(player) }")
            appendLine("        }")
            appendLine("    }")
            appendLine()
            appendLine("    suspend fun QueueTask.make(player: Player) {")
            if (skill != null && recipe.level != null) {
                appendLine("        if (player.getSkills().getCurrentLevel(Skills.$skill) < ${recipe.level}) {")
                appendLine("            player.message(\"You need a ${recipe.skill} level of ${recipe.level} to make ${recipe.output}.\")")
                appendLine("            return")
                appendLine("        }")
            }
            appendLine("        // TODO: animation and the wiki's ${recipe.ticks ?: "?"}-tick duration")
            recipe.materials.forEach { (name, qty) -> appendLine("        player.inventory.remove(getRSCM(${Kt.str(ctx.itemName(name) ?: "item.${RscmNames.slug(name)}")}), ${qty.toIntOrNull() ?: 1})") }
            appendLine("        player.inventory.add(getRSCM(${Kt.str(outputName)}), ${recipe.outputQuantity?.toIntOrNull() ?: 1})")
            if (skill != null && recipe.experience != null) appendLine("        player.addXp(Skills.$skill, ${recipe.experience})")
            appendLine("    }")
            appendLine("}")
        }
        val manual = buildList {
            if (enrichment.recipes.size > 1) add("Only the first of ${enrichment.recipes.size} recipes is generated (${enrichment.recipes.joinToString { it.output }}).")
            add("Animation, timing and failure (e.g. burning) are not on the wiki in a usable form.")
            if (usedId < 0 && onObject) add("The used item id was not recorded on the card.")
        }
        return Scaffold(kind, "Production stub: ${recipe.output} from $material", Kt.branch(kind, recipe.output, id), listOf(ScaffoldFile("${Kt.packagePath(pkg)}/$cls.kt", code)), manual)
    }
}

/** Anything else with a page: a plugin skeleton with the matching hook. */
class SkeletonGenerator : ScaffoldGenerator {
    override val kind = "skeleton"

    override fun supports(enrichment: Enrichment) = true

    override fun generate(enrichment: Enrichment, params: Map<String, Any?>, ctx: ScaffoldContext): Scaffold {
        val id = (params["id"] as Number).toInt()
        val type = params["type"] as? String ?: "UNKNOWN"
        val name = enrichment.facts["name"] as? String ?: enrichment.page?.title ?: params["name"] as? String ?: type.lowercase()
        val option = (params["optionName"] as? String)?.lowercase()
        val pkg = ctx.objPackage()
        val cls = Kt.className("$name ${option ?: type.lowercase()}") + "Plugin"
        val hook = when (type) {
            "NPC_OP" -> "onNpcOption(${Kt.str(ctx.npcName(id, enrichment.page?.title))}, option = ${Kt.str(option ?: "talk-to")})"
            "LOC_OP" -> "onObjOption(${Kt.str(ctx.objName(id, enrichment.page?.title))}, option = ${Kt.str(option ?: "use")})"
            else -> null
        }
        val code = buildString {
            append(Kt.header(pkg, enrichment.sources, "$name: $type${option?.let { " ($it)" } ?: ""}."))
            appendLine("class $cls(r: PluginRepository, world: World, server: Server) : KotlinPlugin(r, world, server) {")
            appendLine("    init {")
            if (hook != null) {
                appendLine("        $hook {")
                appendLine("            player.message(\"TODO: $name $option\")")
                appendLine("        }")
            } else {
                appendLine("        // TODO: $type $id (${enrichment.facts["examine"] ?: "no wiki facts"}); no generated hook for this interaction type.")
            }
            appendLine("    }")
            appendLine("}")
        }
        return Scaffold(kind, "Plugin skeleton for $type on $name", Kt.branch(kind, name, id), listOf(ScaffoldFile("${Kt.packagePath(pkg)}/$cls.kt", code)), listOf("Everything: this is only the hook."))
    }
}
